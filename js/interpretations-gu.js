function guModule(prefix, descriptionBuilder) {
  const result = {};

  for (let number = 1; number <= 9; number += 1) {
    const profile = GujaratiRootProfiles[number];

    result[number] = {
      title: `${prefix} ${number}`,
      theme: profile.theme,
      description: descriptionBuilder(number, profile),
      strengths: [...profile.strengths],
      challenges: [...profile.challenges],
    };
  }

  return result;
}

